const assert=require('assert');
const S=require('./stats-store.js');
const empty=S.createEmpty();
assert.equal(empty.totalCorrect,0);
assert.equal(empty.totalWrong,0);
assert.equal(empty.fastestMs,null);
assert.deepEqual(empty.reactionHistory,[]);
let state=S.record(empty,{type:'correct',mode:'classic',reactionMs:820,combo:3,at:1});
state=S.record(state,{type:'wrong',mode:'classic',at:2});
state=S.record(state,{type:'correct',mode:'classic',reactionMs:640,combo:5,at:3});
assert.equal(state.totalCorrect,2);
assert.equal(state.totalWrong,1);
assert.equal(state.fastestMs,640);
assert.equal(state.maxCombo,5);
assert.equal(Math.round(S.averageReactionMs(state)),730);
assert.equal(state.byMode.classic.correct,2);
assert.equal(state.byMode.classic.wrong,1);
assert.equal(state.reactionHistory.length,2);
for(let i=0;i<40;i++)state=S.record(state,{type:'correct',mode:'sprint:5',reactionMs:1000+i,combo:1,at:10+i});
assert.ok(state.reactionHistory.length<=30);
assert.equal(S.accuracy(state),(42/43)*100);
console.log('stats-store tests OK');
