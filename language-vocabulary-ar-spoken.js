  function fallbackTranslit(text){
    const raw=String(text||'').split('').map(ch=>AR_TO_HE[ch]??ch).join('').replace(/\s+/g,' ').trim();
    if(!raw)return'';
    if(/[\u0591-\u05C7]/.test(raw))return raw;
    const parts=raw.split(/(\s+|[.,!?؟،؛])/);
    return parts.map(part=>{
      if(!/[א-ת]/.test(part))return part;
      let seen=false;
      return part.replace(/[א-ת]/g,ch=>{
        if(seen)return ch+'ְ';
        seen=true;
        return ch+'ַ';
      }).replace(/ְ$/,'');
    }).join('');
  }
