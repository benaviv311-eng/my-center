document.addEventListener('click',async e=>{
  const foldersButton=e.target.closest('#bank-folders-btn');
  if(foldersButton){
    try{
      await bankShowFolders();
    }catch(err){
      toast(err.message||'לא ניתן לפתוח תיקיות');
    }
    return;
  }

  const favoritesButton=e.target.closest('#bank-favs-btn');
  if(favoritesButton){
    try{
      await bankShowFavorites();
    }catch(err){
      toast(err.message||'לא ניתן לפתוח מועדפים');
    }
    return;
  }

  const button=e.target.closest('[data-bank-action]');
  if(!button) return;

  const card=button.closest('[data-bank-id]');
  if(!card) return;

  const itemId=card.dataset.bankId;

  try{
    const action=button.dataset.bankAction;

    if(action==='favorite'){
      const result=await bankWrite({
        action:'toggle_favorite',
        item_id:itemId
      });

      if(result.favorited){
        bankState.favorites.add(itemId);
      }else{
        bankState.favorites.delete(itemId);
      
      }

      button.classList.toggle('active',result.favorited);
      button.textContent=result.favorited?'♥ מועדף':'♡ מועדף';
      toast(result.favorited?'נשמר במועדפים':'הוסר מהמועדפים');
    }

    if(action==='folder'){
      await bankChooseFolder(itemId);
    }

    if(action==='edit'){
      const panel=card.querySelector('.bank-edit');
      panel.hidden=!panel.hidden;
    }

    if(action==='save-edit'){
      const fields={};

      card.querySelectorAll('[data-bank-field]').forEach(el=>{
        fields[el.dataset.bankField]=el.value;
      });

      const result=await bankWrite({
        action:'update_content',
        item_id:itemId,
        fields
      });

      card.querySelector('.bank-context').textContent=
        result.item.content.raika_context||'';

      card.querySelector('.bank-quote').textContent=
        result.item.content.character_quote||'';

      const item=bankState.items.find(x=>x.id===itemId);
      if(item){
        item.content=result.item.content;
      }

      card.querySelector('.bank-edit').hidden=true;
      toast('השינוי נשמר בבנק');
    }

    if(action==='save-note'){
      const note=card.querySelector('[data-bank-note]').value;

      await bankWrite({
        action:'save_note',
        item_id:itemId,
        note_text:note
      });

      bankState.notes.set(itemId,note);
      toast('ההערה נשמרה');
    }
  }catch(err){
    console.error(err);
    toast(err.message||'הפעולה נכשלה');
  }
});

