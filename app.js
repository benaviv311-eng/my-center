async function renderDailyVerses(){
  const wrap=document.getElementById('daily-verses');
  if(!wrap) return;

  ensureBankCss();
  bankToolbar();
  wrap.innerHTML='<div class="bank-loading">טוען פסוקים מהבנק…</div>';

  try{
    const all=await bankPublicVerses();
    bankState.items=all;

    await bankSnapshot().catch(()=>{});

    if(!all.length){
      throw new Error('אין פסוקים בבנק');
    }

    const now=new Date();
    const day=Math.floor(Date.UTC(now.getFullYear(),now.getMonth(),now.getDate())/86400000);
    const start=(day*3)%all.length;
    const picked=[0,1,2].map(i=>all[(start+i)%all.length]);

    wrap.innerHTML=picked.map(bankRenderCard).join('');
  }catch(err){
    console.error(err);
    toast('הבנק לא זמין — מוצגת גרסה מקומית');
    fallbackRender();
  }
}

async function bankChooseFolder(itemId){
  await bankSnapshot(true);

  const list=bankState.folders
    .map((folder,index)=>`${index+1}. ${folder.name}`)
    .join('\n');

  const answer=(prompt(
`${list||'אין עדיין תיקיות.'}

כתוב מספר תיקייה,
או +שם כדי ליצור תיקייה חדשה:`
  )||'').trim();

  if(!answer) return;

  let folder;

  if(answer.startsWith('+')){
    const name=answer.slice(1).trim();
    if(!name) return;

    const result=await bankWrite({
      action:'create_folder',
      name
    });

    folder=result.folder;
    bankState.folders.push(folder);
  }else{
    const number=Number(answer);

    if(!Number.isInteger(number) || number<1 || number>bankState.folders.length){
      throw new Error('מספר תיקייה לא תקין');
    }

    folder=bankState.folders[number-1];
  }

  await bankWrite({
    action:'add_to_folder',
    item_id:itemId,
    folder_id:folder.id
  });

  bankState.snapshotLoaded=false;
  toast(`נשמר בתיקייה: ${folder.name}`);
}

async function bankShowFolders(){
  await bankSnapshot(true);

  if(!bankState.folders.length){
    alert('עדיין אין תיקיות');
    return;
  }

  const lines=bankState.folders.map(folder=>{
    const count=bankState.folderItems.filter(x=>x.folder_id===folder.id).length;
    return `📁 ${folder.name} — ${count} פריטים`;
  });

  alert(lines.join('\n'));
}

async function bankShowFavorites(){
  await bankSnapshot(true);

  const names=bankState.items
    .filter(item=>bankState.favorites.has(item.id))
    .map(item=>`♥ ${item.title}`);

  alert(names.length?names.join('\n'):'עדיין אין פסוקים במועדפים');
}

