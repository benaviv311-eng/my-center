async function bankPublicVerses(){
  const url=`${BANK_URL}/rest/v1/content_items?item_type=eq.verse&status=eq.published&visibility=eq.public&select=id,slug,title,content,updated_at,created_at&order=created_at.asc`;
  const response=await fetch(url,{
    headers:{
      apikey:BANK_PUBLISHABLE_KEY
    }
  });

  if(!response.ok){
    throw new Error(`קריאת הבנק נכשלה (${response.status})`);
  }

  return response.json();
}

function bankStoredKey(){
  return localStorage.getItem(BANK_EDITOR_KEY)||'';
}

async function bankGetEditorKey(){
  let key=bankStoredKey();

  if(!key){
    key=(prompt('הכנס קוד עריכה פרטי כדי לשמור בענן:')||'').trim();

    if(!key){
      throw new Error('לא הוזן קוד עריכה');
    }

    localStorage.setItem(BANK_EDITOR_KEY,key);
  }

  return key;
}

async function bankWrite(payload){
  const key=await bankGetEditorKey();

  const response=await fetch(BANK_FUNCTION,{
    method:'POST',
    headers:{
      'content-type':'application/json',
      'apikey':BANK_PUBLISHABLE_KEY,
      'x-editor-key':key
    },
    body:JSON.stringify(payload)
  });

  const data=await response.json().catch(()=>({}));

  if(response.status===401){
    localStorage.removeItem(BANK_EDITOR_KEY);
    bankState.snapshotLoaded=false;
    throw new Error('קוד העריכה אינו תקין');
  }

  if(!response.ok || data.error){
    throw new Error(data.error||`שמירה נכשלה (${response.status})`);
  }

  return data;
}

async function bankSnapshot(force=false){
  if(bankState.snapshotLoaded && !force) return;
  if(!bankStoredKey()) return;

  const snapshot=await bankWrite({action:'snapshot'});

  bankState.favorites=new Set((snapshot.favorites||[]).map(x=>x.item_id));
  bankState.folders=snapshot.folders||[];
  bankState.folderItems=snapshot.folder_items||[];
  bankState.notes=new Map((snapshot.notes||[]).map(x=>[x.item_id,x.note_text||'']));
  bankState.snapshotLoaded=true;
}

